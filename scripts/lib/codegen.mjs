// Writes the generated artifacts: dataset JSON, runtime (verbatim engine copy)
// and readable MSW handlers. Output is deterministic so it can be committed and diffed.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { embedLabel } from './scenario.mjs';

const ENGINE_FILE = join(dirname(fileURLToPath(import.meta.url)), 'contract.mjs');

export function datasetJson(dataset) {
  return `${JSON.stringify(dataset, null, 2)}\n`;
}

/**
 * @param {object} dataset
 * @param {{ importBase?: string }} [opts] relative path from the handlers file to the
 *   folder holding <scenario>.json and runtime.mjs (default './': same folder).
 */
export function handlersSource(dataset, { importBase = './' } = {}) {
  const name = dataset.scenario;
  const base = importBase.endsWith('/') ? importBase : `${importBase}/`;
  const hasLatency = dataset.endpoints.some((ep) => ep.latency !== undefined);
  const lines = [
    '// Generated by atrezzo. Do not edit by hand: change the scenario and run `atrezzo world`.',
    `// Scenario: ${name} · seed ${dataset.seed} · now ${dataset.now} · hash ${dataset.hash}`,
    hasLatency ? "import { http, HttpResponse, delay } from 'msw';" : "import { http, HttpResponse } from 'msw';",
    `import dataset from '${base}${name}.json' with { type: 'json' };`,
    `import { createEngine } from '${base}runtime.mjs';`,
    '',
    'const engine = createEngine(dataset);',
    '',
    '/** Projects the request with the same engine as `atrezzo serve`. */',
    'function project({ request }) {',
    '  const url = new URL(request.url);',
    '  const res = engine.handle({ method: request.method, pathname: url.pathname, query: url.searchParams, headers: request.headers });',
    '  if (!res) return undefined; // not ours: MSW moves on to the next handler',
    '  // HEAD never carries a body, the same as in `serve`.',
    '  if (request.method === \'HEAD\') return new HttpResponse(null, { status: res.status, headers: res.headers });',
    '  if (res.hasBody === false || (res.hasBody === undefined && res.body === null)) return new HttpResponse(null, { status: res.status, headers: res.headers }); // count only or empty body',
    "  if (typeof res.body === 'string' && !/\\bjson\\b|\\+json/i.test(res.headers['content-type'] ?? '')) return new HttpResponse(res.body, { status: res.status, headers: res.headers });",
    '  return HttpResponse.json(res.body, { status: res.status, headers: res.headers });',
    '}',
  ];
  lines.push(
    '',
    '/** CORS preflight: `serve` answers 204 to every OPTIONS with these headers, so the handlers do the same. */',
    "const preflight = () => new HttpResponse(null, { status: 204, headers: { 'access-control-allow-origin': '*', 'access-control-allow-methods': 'GET, POST, PUT, PATCH, DELETE', 'access-control-allow-headers': 'content-type, authorization, prefer' } });",
    '',
    '/**',
    ' * A contract route asked with a method the contract does not declare. Registered after every real',
    ' * handler: the engine sees the real method and answers its own 405 (with the right `Allow`), the same',
    ' * as `serve`; a route the engine does not know is left alone so MSW moves on.',
    ' */',
    'function methodNotAllowed(info) {',
    "  if (info.request.method === 'OPTIONS') return preflight();",
    '  return project(info);',
    '}',
  );
  if (hasLatency) {
    lines.push(
      '',
      '/** `latency:` on the endpoint, the same wait `serve` does. */',
      'const withLatency = (ms, handler) => async (info) => { await delay(ms); return handler(info); };',
    );
  }
  if (dataset.writes?.length || dataset.rpc?.length) {
    lines.push(
      '',
      '/** Applies a declared write against the in-memory world, or answers a declared PostgREST function (rpc). */',
      'async function mutate({ request }) {',
      '  const url = new URL(request.url);',
      '  const text = await request.text();',
      '  let body = {};',
      '  if (text) {',
      '    try { body = JSON.parse(text); } catch {',
      "      return HttpResponse.json({ error: 'invalid JSON body' }, { status: 400, headers: { 'x-atrezzo-scenario': dataset.scenario } });",
      '    }',
      '  }',
      '  const res = engine.handle({ method: request.method, pathname: url.pathname, query: url.searchParams, headers: request.headers, body });',
      '  if (!res) return undefined;',
      '  if (res.hasBody === false || (res.hasBody === undefined && res.body === null)) return new HttpResponse(null, { status: res.status, headers: res.headers });',
      '  return HttpResponse.json(res.body, { status: res.status, headers: res.headers });',
      '}',
    );
  }
  const fallbacks = new Set();
  lines.push('', 'export const handlers = [');
  for (const ep of dataset.endpoints) {
    const notes = [ep.passthrough ? `passthrough: ${ep.passthrough.fixture}` : `${ep.entity}`];
    if (ep.filters.length) notes.push(`filters: ${ep.filters.join(', ')}`);
    if (ep.worldFilters?.length) notes.push(`world filters: ${ep.worldFilters.map((w) => `${w.field}→${w.from}`).join(', ')}`);
    if (ep.userFilters?.length) notes.push(`user filters: ${ep.userFilters.map((u) => `${u.field}=$user.${u.userField}`).join(', ')}`);
    if (ep.pagination) notes.push(`pagination: ${ep.pagination.limit}/${ep.pagination.offset}`);
    if (ep.sorts) notes.push(`sorts: ${ep.sorts.by}${ep.sorts.order ? `/${ep.sorts.order}` : ''} (${ep.sorts.fields.join(', ')})`);
    if (ep.scopes?.length) notes.push(`scopes: ${ep.scopes.map((s) => `${s.param}→${s.field}`).join(', ')}`);
    if (ep.envelope) notes.push(`envelope: ${Object.entries(ep.envelope).map(([k, v]) => `${k}→${v}`).join(', ')}`);
    else if (ep.pick) notes.push(`envelope: ${ep.pick}`);
    if (ep.wrap) notes.push(`wrap: ${ep.wrap}`);
    if (ep.include.length) notes.push(`includes: ${ep.include.join(', ')}`);
    if (ep.embed?.length) notes.push(`embeds: ${embedLabel(ep.embed)}`);
    if (ep.counts?.length) notes.push(`counts: ${ep.counts.map((c) => `${c.field}=${c.entity}.${c.on}`).join(', ')}`);
    if (ep.pluck) notes.push(`pluck: ${ep.pluck}`);
    if (ep.error) notes.push(`error: ${ep.error.status}`);
    if (ep.params) notes.push(`params: ${ep.params.map((x) => `:${x.name}→${x.field ?? 'any'}`).join(', ')}`);
    lines.push(`  // ${ep.path} → ${notes.join(' · ')}`);
    const handler = ep.latency !== undefined ? `withLatency(${ep.latency}, project)` : 'project';
    lines.push(`  http.get('*${ep.path}', ${handler}),`);
    // HEAD too: supabase-js asks for counts with `head: true` and would otherwise hit the network.
    lines.push(`  http.head('*${ep.path}', ${handler}),`);
    // MSW and the engine share the ":name" syntax; the detail segment must not reuse a parameter's name.
    if (ep.detail) {
      const detail = `*${ep.path}/:${ep.params?.some((x) => x.name === 'id') ? 'row_id' : 'id'}`;
      lines.push(`  http.get('${detail}', ${handler}),`);
      lines.push(`  http.head('${detail}', ${handler}),`);
    }
    // Undeclared methods answer 405 here as in `serve` (they used to escape to the network in MSW).
    fallbacks.add(`*${ep.path}`);
    if (ep.detail) fallbacks.add(`*${ep.path}/:${ep.params?.some((x) => x.name === 'id') ? 'row_id' : 'id'}`);
  }
  for (const w of dataset.writes ?? []) fallbacks.add(`*${w.path}`);
  if (dataset.rpc?.length) fallbacks.add('*/rpc/:fn');
  for (const st of dataset.streams ?? []) {
    // The msw adapter cannot emit SSE: an explicit 501 beats a flow that fails silently.
    lines.push(`  // streams ${st.path} → 501 (the msw adapter does not emit SSE)`);
    lines.push(`  http.get('*${st.path}', () => HttpResponse.json({ error: 'SSE streams are not supported by the msw adapter: use atrezzo serve' }, { status: 501, headers: { 'x-atrezzo-unsupported': 'streams' } })),`);
  }
  if (dataset.rpc?.length) {
    // One handler for every function: it covers /rpc/<fn> and /rest/v1/rpc/<fn>; an undeclared one answers 404 (gap).
    // Registered before writes so declared RPCs keep precedence even if a synthetic dataset has an overlapping write.
    lines.push(`  // rpc → ${dataset.rpc.map((r) => `${r.fn} (${r.expect.status}${r.match ? `, match: ${Object.keys(r.match).join(', ')}` : ''})`).join(' · ')}`);
    lines.push("  http.post('*/rpc/:fn', mutate),");
  }
  if (dataset.writes?.length) {
    const orderedWrites = [...dataset.writes].sort((a, b) => (a.params?.length ?? 0) - (b.params?.length ?? 0));
    for (const w of orderedWrites) {
      const notes = [`status ${w.expect.status}${w.expect.echo ? ' · echo' : ''}`];
      if (w.mutate) notes.push(`${w.mutate.action} ${w.mutate.entity}${w.inferred ? ` (inferred from GET ${w.inferred})` : ''}`);
      lines.push(`  // ${w.method} ${w.path} → ${notes.join(' · ')}`);
      lines.push(`  http.${w.method.toLowerCase()}('*${w.path}', mutate),`);
    }
    lines.push("  http.post('*/__atrezzo/reset', () => { engine.reset(); return HttpResponse.json({ scenario: dataset.scenario, reset: true }, { status: 200 }); }),");
  }
  if (fallbacks.size) {
    // Last, so a declared write keeps winning: methods the contract does not declare answer 405 and
    // OPTIONS answers 204, like `serve`.
    lines.push('  // Methods the contract does not declare: 405 (OPTIONS: 204), like `serve`.');
    for (const path of fallbacks) lines.push(`  http.all('${path}', methodNotAllowed),`);
  }
  lines.push('];', '', 'export function reset() { engine.reset(); }', '', 'export { dataset };', '');
  return lines.join('\n');
}

export function engineSource() {
  return readFileSync(ENGINE_FILE, 'utf8');
}

/**
 * Write the source of truth: <dir>/<name>.json and <dir>/runtime.mjs.
 * With `{ handlers: true }` also <dir>/<name>.handlers.mjs (0.1 behaviour).
 */
export function writeGenerated(dataset, dir, { handlers = true } = {}) {
  mkdirSync(dir, { recursive: true });
  const files = {
    json: join(dir, `${dataset.scenario}.json`),
    runtime: join(dir, 'runtime.mjs'),
  };
  writeFileSync(files.json, datasetJson(dataset));
  writeFileSync(files.runtime, engineSource());
  if (handlers) {
    files.handlers = join(dir, `${dataset.scenario}.handlers.mjs`);
    writeFileSync(files.handlers, handlersSource(dataset));
  }
  return files;
}
