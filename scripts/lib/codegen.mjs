// Writes the generated artifacts: dataset JSON, runtime (verbatim engine copy)
// and readable MSW handlers. Output is deterministic so it can be committed and diffed.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { embedLabel } from './scenario.mjs';

const ENGINE_FILE = join(dirname(fileURLToPath(import.meta.url)), 'contract.mjs');

export function datasetJson(dataset) {
  return `${JSON.stringify(dataset, null, 2)}\n`;
}

/**
 * @param {object} dataset
 * @param {{ importBase?: string }} [opts] relative path from the handlers file to the
 *   folder holding <scenario>.json and runtime.mjs (default './': same folder).
 */
export function handlersSource(dataset, { importBase = './' } = {}) {
  const name = dataset.scenario;
  const base = importBase.endsWith('/') ? importBase : `${importBase}/`;
  const lines = [
    '// Generated by atrezzo. Do not edit by hand: change the scenario and run `atrezzo world`.',
    `// Scenario: ${name} · seed ${dataset.seed} · now ${dataset.now} · hash ${dataset.hash}`,
    "import { http, HttpResponse } from 'msw';",
    `import dataset from '${base}${name}.json' with { type: 'json' };`,
    `import { createEngine } from '${base}runtime.mjs';`,
    '',
    'const engine = createEngine(dataset);',
    '',
    '/** Projects the request with the same engine as `atrezzo serve`. */',
    'function project({ request }) {',
    '  const url = new URL(request.url);',
    '  const res = engine.handle({ method: request.method, pathname: url.pathname, query: url.searchParams, headers: request.headers });',
    '  if (!res) return undefined; // not ours: MSW moves on to the next handler',
    '  if (res.body === null) return new HttpResponse(null, { status: res.status, headers: res.headers }); // count only',
    '  return HttpResponse.json(res.body, { status: res.status, headers: res.headers });',
    '}',
    '',
    'export const handlers = [',
  ];
  for (const ep of dataset.endpoints) {
    const notes = [`${ep.entity}`];
    if (ep.filters.length) notes.push(`filters: ${ep.filters.join(', ')}`);
    if (ep.worldFilters?.length) notes.push(`world filters: ${ep.worldFilters.map((w) => `${w.field}→${w.from}`).join(', ')}`);
    if (ep.userFilters?.length) notes.push(`user filters: ${ep.userFilters.map((u) => `${u.field}=$user.${u.userField}`).join(', ')}`);
    if (ep.pagination) notes.push(`pagination: ${ep.pagination.limit}/${ep.pagination.offset}`);
    if (ep.sorts) notes.push(`sorts: ${ep.sorts.by}${ep.sorts.order ? `/${ep.sorts.order}` : ''} (${ep.sorts.fields.join(', ')})`);
    if (ep.include.length) notes.push(`includes: ${ep.include.join(', ')}`);
    if (ep.embed?.length) notes.push(`embeds: ${embedLabel(ep.embed)}`);
    if (ep.pluck) notes.push(`pluck: ${ep.pluck}`);
    if (ep.error) notes.push(`error: ${ep.error.status}`);
    if (ep.params) notes.push(`params: ${ep.params.map((x) => `:${x.name}→${x.field ?? 'any'}`).join(', ')}`);
    lines.push(`  // ${ep.path} → ${notes.join(' · ')}`);
    lines.push(`  http.get('*${ep.path}', project),`);
    // MSW and the engine share the ":name" syntax; the detail segment must not reuse a parameter's name.
    if (ep.detail) lines.push(`  http.get('*${ep.path}/:${ep.params?.some((x) => x.name === 'id') ? 'row_id' : 'id'}', project),`);
  }
  lines.push('];', '', 'export { dataset };', '');
  return lines.join('\n');
}

export function engineSource() {
  return readFileSync(ENGINE_FILE, 'utf8');
}

/**
 * Write the source of truth: <dir>/<name>.json and <dir>/runtime.mjs.
 * With `{ handlers: true }` also <dir>/<name>.handlers.mjs (0.1 behaviour).
 */
export function writeGenerated(dataset, dir, { handlers = true } = {}) {
  mkdirSync(dir, { recursive: true });
  const files = {
    json: join(dir, `${dataset.scenario}.json`),
    runtime: join(dir, 'runtime.mjs'),
  };
  writeFileSync(files.json, datasetJson(dataset));
  writeFileSync(files.runtime, engineSource());
  if (handlers) {
    files.handlers = join(dir, `${dataset.scenario}.handlers.mjs`);
    writeFileSync(files.handlers, handlersSource(dataset));
  }
  return files;
}
