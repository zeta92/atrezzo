// supabase: there is no mock layer in Supabase — its API is PostgREST over
// Postgres. So the "runtime" is the database itself: we emit schema.sql (minimal
// tables, only if missing), seed.sql (idempotent truncate + inserts of the world)
// and reset.sh. Filtering/pagination are then PostgREST's, not atrezzo's.
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { columnInfo, entityOrder, metaFrom, p } from './common.mjs';

function signals(ctx) {
  const out = [];
  const toml = ctx.files('supabase/config.toml');
  if (toml.length) out.push({ text: `${toml[0]} (Supabase CLI project)`, weight: 3 });
  const dep = ctx.dep('@supabase/supabase-js');
  if (dep) out.push({ text: `@supabase/supabase-js in ${dep}`, weight: 2 });
  if (!toml.length) {
    const dir = ctx.files('supabase');
    if (dir.length) out.push({ text: `folder ${dir[0]}/`, weight: 2 });
  }
  const envKey = Object.keys(ctx.env).sort().find((k) => /SUPABASE_URL$/.test(k));
  if (envKey) out.push({ text: `${envKey} in ${ctx.env[envKey].file}`, weight: 2 });
  return out;
}

export const meta = metaFrom({
  id: 'supabase',
  label: 'Supabase (seed.sql for Postgres + PostgREST)',
  signals,
  none: 'no supabase/, @supabase/supabase-js or SUPABASE_URL',
  startHint: 'DATABASE_URL=… <dir>/reset.sh (Supabase CLI or local Postgres + PostgREST)',
});

const PG_TYPE = { integer: 'bigint', number: 'numeric', boolean: 'boolean', datetime: 'timestamptz', string: 'text' };
const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;
export function sqlLiteral(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** Where the files go: next to <backend>/supabase if it exists, else under generatedDir. */
export function outDir({ config, dir, dataset }) {
  const backend = config.workspace?.backend;
  for (const base of [backend && backend !== '.' ? p(backend, 'supabase') : null, 'supabase']) {
    if (base && existsSync(join(dir, base))) return p(base, 'atrezzo', dataset.scenario);
  }
  return p(config.generatedDir, 'supabase', dataset.scenario);
}

function header(dataset, what) {
  return [
    `-- Generated by atrezzo (${what}). Do not edit by hand: change the scenario and run \`atrezzo world\`.`,
    `-- Scenario: ${dataset.scenario} · seed ${dataset.seed} · now ${dataset.now} · hash ${dataset.hash}`,
  ];
}

export function schemaSql(dataset) {
  const order = entityOrder(dataset);
  const out = [...header(dataset, 'minimal schema'),
    '-- Only for a LOCAL database without migrations. CREATE TABLE IF NOT EXISTS leaves existing',
    '-- tables alone: if your migrations create them with other columns, seed.sql will fail',
    '-- with "column ... does not exist" (which is correct: the scenario does not match your schema).',
    '',
    'SET client_min_messages = warning;',
    ''];
  for (const name of order) {
    const meta = dataset.schema[name];
    const rows = dataset.entities[name];
    const cols = meta.fields.map((f) => {
      if (f === 'id') return `  ${ident('id')} bigint PRIMARY KEY`;
      const info = columnInfo(rows, f);
      const ref = meta.refs[f];
      return `  ${ident(f)} ${PG_TYPE[info.type]}${info.nullable || !rows.length ? '' : ' NOT NULL'}${ref ? ` REFERENCES ${ident(ref)} (${ident('id')})` : ''}`;
    });
    out.push(`CREATE TABLE IF NOT EXISTS ${ident(name)} (`, cols.join(',\n'), ');', '');
  }
  out.push('-- PostgREST/Supabase: read access for the anonymous role if it exists (Supabase creates it; standalone PostgREST, per your config).',
    'DO $$',
    'BEGIN',
    "  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN",
    `    GRANT SELECT ON ${order.map(ident).join(', ')} TO anon;`,
    '  END IF;',
    'END',
    '$$;', '');
  return out.join('\n');
}

export function seedSql(dataset) {
  const order = entityOrder(dataset);
  const out = [...header(dataset, 'data'),
    '-- Idempotent: empties the scenario tables and re-inserts the world with stable ids.',
    '-- TRUNCATE ... CASCADE also empties tables that reference these: use it locally only.',
    '',
    'SET client_min_messages = warning;',
    'BEGIN;',
    `TRUNCATE TABLE ${[...order].reverse().map(ident).join(', ')} RESTART IDENTITY CASCADE;`,
    ''];
  for (const name of order) {
    const { fields } = dataset.schema[name];
    const rows = dataset.entities[name];
    out.push(`-- ${name}: ${rows.length} rows`);
    for (let i = 0; i < rows.length; i += 500) {
      const chunk = rows.slice(i, i + 500);
      // OVERRIDING SYSTEM VALUE: works with GENERATED ALWAYS identity ids too.
      out.push(`INSERT INTO ${ident(name)} (${fields.map(ident).join(', ')}) OVERRIDING SYSTEM VALUE VALUES`);
      out.push(`${chunk.map((r) => `  (${fields.map((f) => sqlLiteral(r[f])).join(', ')})`).join(',\n')};`);
    }
    // If the real table has a serial/identity id, move the sequence past our ids.
    const seq = `pg_get_serial_sequence('${ident(name).replace(/'/g, "''")}', 'id')`;
    out.push(`DO $$ BEGIN PERFORM setval(${seq}, GREATEST((SELECT max(${ident('id')}) FROM ${ident(name)}), 1)) WHERE ${seq} IS NOT NULL; END $$;`);
    out.push('');
  }
  out.push('COMMIT;', '');
  return out.join('\n');
}

function resetSh(dataset, total) {
  return `#!/usr/bin/env sh
# Generated by atrezzo. Restores scenario "${dataset.scenario}" (hash ${dataset.hash}) into a LOCAL Postgres.
# Idempotent: run it as many times as you like (CREATE IF NOT EXISTS + TRUNCATE + INSERT).
set -eu
: "\${DATABASE_URL:=postgresql://postgres:postgres@127.0.0.1:54322/postgres}"
case "$DATABASE_URL" in
  *localhost*|*127.0.0.1*|*@db:*|*@postgres:*|*host.docker.internal*) ;;
  *)
    if [ "\${ATREZZO_ALLOW_REMOTE:-}" != "1" ]; then
      echo "atrezzo: DATABASE_URL does not look local and this script runs TRUNCATE. Export ATREZZO_ALLOW_REMOTE=1 if you really mean it." >&2
      exit 2
    fi ;;
esac
command -v psql >/dev/null 2>&1 || { echo "atrezzo: psql (PostgreSQL client) is missing" >&2; exit 2; }
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -q -f "$here/schema.sql"
psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -q -f "$here/seed.sql"
echo "atrezzo: scenario ${dataset.scenario} restored (${total} rows)"
`;
}

function readme(dataset, dir) {
  const tables = Object.keys(dataset.schema);
  const ep = dataset.endpoints.map((e) => `| \`${e.path}\` | \`/rest/v1/${e.entity}\`${e.filters.length ? ` (\`?${e.filters[0]}=eq.<value>\`)` : ''} |`).join('\n');
  return `# Scenario \`${dataset.scenario}\` for Supabase

Generated by atrezzo (hash \`${dataset.hash}\`). Supabase has no mock layer: its API is PostgREST over Postgres,
so the "mock" is **the local database with the world loaded**. Tables: ${tables.map((t) => `\`${t}\``).join(', ')}.

| file | what it does |
|---|---|
| \`schema.sql\` | minimal \`CREATE TABLE IF NOT EXISTS\` (only if you have no migrations) |
| \`seed.sql\` | \`TRUNCATE … RESTART IDENTITY CASCADE\` + \`INSERT\` with stable ids, in one transaction |
| \`reset.sh\` | applies both with \`psql\`; refuses to touch a non-local \`DATABASE_URL\` |

## Option A: Supabase CLI (recommended)

\`\`\`bash
supabase start                        # Postgres on :54322, API on :54321 (PostgREST + GoTrue)
DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:54322/postgres ${dir}/reset.sh
\`\`\`

Or let \`supabase db reset\` load it: in \`supabase/config.toml\`, \`[db.seed]\` → \`sql_paths = ["./atrezzo/${dataset.scenario}/seed.sql"]\`
(the path is relative to \`supabase/\`; check that your CLI version supports \`sql_paths\`). Your \`supabase/seed.sql\` is left alone.

## Option B: standalone Postgres + PostgREST

\`\`\`bash
docker run -d --name atrezzo-pg -e POSTGRES_PASSWORD=postgres -p 54322:5432 postgres:16
DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:54322/postgres ${dir}/reset.sh
docker run --rm -p 3000:3000 -e PGRST_DB_URI=postgresql://postgres:postgres@host.docker.internal:54322/postgres \\
  -e PGRST_DB_ANON_ROLE=postgres -e PGRST_DB_SCHEMAS=public postgrest/postgrest
# GoTrue (auth) is not included: if the app needs a session, use option A.
\`\`\`

## What changes compared to \`atrezzo serve\`

| scenario | PostgREST |
|---|---|
${ep}

- The scenario routes (\`${dataset.endpoints[0]?.path ?? '/api/…'}\`) **do not exist** here: supabase-js queries \`/rest/v1/<table>\`.
- PostgREST, not the atrezzo engine, handles filters, sorting, pagination (\`Range\`, \`limit/offset\`) and joins (\`select=*,customer:customers(*)\`).
  The data is the same (same ids and rows); the projection is not byte-for-byte the one from \`serve\`.
- RLS: if your migrations enable RLS, the \`anon\` role only sees what your policies allow. atrezzo does not simulate RLS.
- Auth/Storage/Realtime: out of scope; they come from the local Supabase in option A.
`;
}

export function emit({ dataset, config, dir }) {
  const out = outDir({ config, dir, dataset });
  const total = Object.values(dataset.entities).reduce((s, r) => s + r.length, 0);
  return {
    files: [
      { path: p(out, 'schema.sql'), content: schemaSql(dataset) },
      { path: p(out, 'seed.sql'), content: seedSql(dataset) },
      { path: p(out, 'reset.sh'), content: resetSh(dataset, total), mode: 0o755 },
      { path: p(out, 'README.md'), content: readme(dataset, out) },
    ],
    start: `DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:54322/postgres ${out}/reset.sh   (after supabase start)`,
    notes: [
      `${total} rows in ${Object.keys(dataset.entities).length} tables; stable ids 1..n (the same as in serve/msw)`,
      'the app queries /rest/v1/<entity> (PostgREST): the scenario routes are not used; PostgREST does filtering and pagination',
      'does not simulate RLS or auth: with RLS on, the anon role only sees what your policies allow',
      out.startsWith(p(config.generatedDir)) ? 'no supabase/ folder: files go to .generated (pass --backend if it lives elsewhere)' : `next to ${out.split('/atrezzo/')[0]}; your supabase/seed.sql is left alone`,
    ],
  };
}
